import { Badge } from "./ui/badge";

/**
 * The provenance chip (brief v3 §2): every number, panel and chart carries exactly one. MODELLED values link to their
 * inputs and assumptions; synthetic, replay or modelled data is never shown as live.
 */
export type DataLabelKind = "LIVE" | "DELAYED" | "REPLAY" | "SYNTHETIC" | "MODELLED" | "ILLUSTRATIVE";
const TONE: Record<DataLabelKind, "ok" | "info" | "warn" | "neutral" | "gold"> = { LIVE: "ok", DELAYED: "warn", REPLAY: "info", SYNTHETIC: "neutral", MODELLED: "gold", ILLUSTRATIVE: "neutral" };
const HINT: Record<DataLabelKind, string> = {
  LIVE: "Fetched from a real feed within its freshness window",
  DELAYED: "Real feed, older than its freshness window",
  REPLAY: "Recorded real data played back",
  SYNTHETIC: "Generated by our seed scripts; not client data",
  MODELLED: "Computed by the engine from labelled inputs and assumptions",
  ILLUSTRATIVE: "An example value with no computation behind it",
};
export function DataLabel({ kind, className }: { kind: DataLabelKind; className?: string }) {
  return <Badge tone={TONE[kind]} className={`font-mono tracking-[0.12em] ${className ?? ""}`} title={HINT[kind]}>{kind}</Badge>;
}
